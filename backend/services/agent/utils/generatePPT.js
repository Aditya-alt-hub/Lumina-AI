export const generatePPT=async (data)=>
{
    const ppt=new pptxgen()

    ppt.layout="LAYOUT_WIDE"
    ppt.author="SexyAI"
    ppt.title=data.title
    ppt.subject=data.title
    ppt.company="SexyAI"
    // ppt.lang="en-US"
    ppt.theme={
        headFontFace:"Aptos",
        bodyFontFace:"Aptos",
        // lang:"en-US"

    }

    addCoverPage(ppt,data)

    data?.slides?.forEach((s,index) => {
        addContentSlide(
            ppt,
            s.title,
            s.points,
            s.visual,
            index+1,
            data.slides.length
        )
    });

    addThankyou(ppt)

    return ppt
}

